#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Avino — сид юр-документов (Правила/Политика) в legal_documents как v1 PUBLISHED.
#
# Зачем: если таблица пуста, /admin/legal ничего не показывает, а API /legal/*
# отдаёт 404 (публичные страницы при этом живут на вшитом фолбэке content/legal).
# Миграции создают пустую таблицу — начальную версию заливает этот сид.
#
# Идемпотентно per kind: если по kind уже есть ЛЮБАЯ строка (draft/published/
# archived) — пропускает, работу админа не затирает. Значит запускать можно
# сколько угодно раз; реально заливает только на пустой БД.
#
# Запуск на сервере из корня репозитория:
#   ./deploy/legalSeed.sh
#
# Вызывается также из deploy/deploy.sh (best-effort) после того, как api healthy.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

# Корень репозитория = родитель каталога этого скрипта.
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

COMPOSE=(docker compose -f docker-compose.yml -f docker-compose.prod.yml --profile app)

# -T: без TTY (скрипт может вызываться из деплоя, где терминала нет).
exec "${COMPOSE[@]}" exec -T api node prisma/seed-legal.cjs
